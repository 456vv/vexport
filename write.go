package main

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// fileWriter persists rendered files.
//
// Safety rules:
//   - it refuses to overwrite a file it did not generate (unless -force),
//     because -o usually points into a source tree;
//   - it never writes anything when the pipeline failed earlier: write is the
//     last stage, after -verify;
//   - several files require -o to be a directory (or a file prefix), stdout
//     only ever receives exactly one file.
type fileWriter struct{}

const generatedMarker = "Code generated by vexport"

func (fileWriter) Write(ctx context.Context, files []File, cfg *Config) error {
	if len(files) == 0 {
		return errors.New("no output files")
	}
	if cfg.Out == "" || cfg.Out == "-" {
		if len(files) > 1 {
			return fmt.Errorf("%d output files; use -o DIR to write them", len(files))
		}
		if _, err := os.Stdout.Write(files[0].Content); err != nil {
			return err
		}
		files[0].Path = "-"
		return nil
	}

	isDir := filepath.Ext(cfg.Out) != ".go"
	if info, err := os.Stat(cfg.Out); err == nil && info.IsDir() {
		isDir = true
	}
	if strings.HasSuffix(cfg.Out, "/") || strings.HasSuffix(cfg.Out, string(os.PathSeparator)) {
		isDir = true
	}

	for i := range files {
		var target string
		switch {
		case isDir:
			target = filepath.Join(cfg.Out, files[i].Name)
		case len(files) == 1:
			target = cfg.Out
		default:
			base := strings.TrimSuffix(cfg.Out, ".go")
			slug := files[i].Slug
			if slug == "" {
				slug = fmt.Sprintf("part%d", i+1)
			}
			target = base + "_" + slug + ".go"
		}
		if err := guardOverwrite(target, cfg); err != nil {
			return err
		}
		if err := writeFile(target, files[i].Content); err != nil {
			return err
		}
		files[i].Path = target
	}
	return nil
}

// guardOverwrite refuses to clobber a hand written file.
func guardOverwrite(path string, cfg *Config) error {
	// -force 是错误信息里已经承诺的逃生口；没有这个判断时旗标不存在，手写文件无法覆盖。
	if cfg != nil && cfg.Force {
		return nil
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return nil // does not exist yet
	}
	if strings.Contains(string(b), generatedMarker) {
		return nil
	}
	return fmt.Errorf("refusing to overwrite %s: it was not generated by extractor (use -force)", path)
}

func writeFile(path string, content []byte) error {
	dir := filepath.Dir(path)
	if dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	return os.WriteFile(path, content, 0o644)
}
